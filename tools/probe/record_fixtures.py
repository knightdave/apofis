#!/usr/bin/env python3
"""Record live Hermes API server responses as test fixtures for Apofis.

Usage:
  APOFIS_TEST_URL=http://127.0.0.1:8642 APOFIS_TEST_KEY=... \
    python3 tools/probe/record_fixtures.py [--only NAME[,NAME...]] [--list] [--self-test]

Rules this script enforces:
- Session ids are "apofis-probe-<time>-<name>-<32 hex from secrets.token_hex(16)>", generated by
  this invocation and tracked (with the source sent) before the create request. Cleanup first
  GETs each tracked id: 404 means nothing to delete; it deletes only a row whose source is the one
  sent and whose title is exactly a unique title this invocation sent for that id (an empty or
  missing title does not count). Any other answer leaves the
  session alone, reports its id and makes the exit status non-zero. A create that answers 409
  means the id was not ours to create: it is untracked, never deleted.
- The only list request filters by a title this invocation sent (never one taken from server
  output), refuses an empty title, and drops rows whose id is not owned before anything else
  reads the body. The 401/404 probes target random probe ids.
- Every body passes through `sanitize()` before it is queued, written or printed: each JSON
  document and each SSE `data:` payload is decoded, the whole tree is checked for the API key,
  token/cost counters are replaced with fixed placeholders, and served model/provider identifiers
  become `example-*`. A `.json` fixture must decode to the top-level object its name expects and
  an `.sse` fixture must carry data frames. Error paths print only this script's own messages.
- A scenario's fixtures are written only when every check passed (status codes, error codes,
  session and run ids in every receipt, PATCH values and DELETE results as sent, event sequence
  and order, terminal state).

Standard library only.
"""
