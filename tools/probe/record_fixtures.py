# ---------------------------------------------------------------- HTTP helpers

def conn(timeout=60):
    cls = http.client.HTTPSConnection if URL.scheme == "https" else http.client.HTTPConnection
    return cls(URL.hostname, URL.port, timeout=timeout)


class Resp:
    def __init__(self, status, headers, raw):
        self.status, self.headers, self.raw = status, headers, raw

    def json(self):
        return json.loads(self.raw)

    def code(self):
        try:
            return self.json().get("error", {}).get("code")
        except Exception:
            return None


def request(method, path, body=None, headers=None, auth=True, owned_rows=False):
    h = {"Accept": "application/json"}
    if auth:
        h["Authorization"] = f"Bearer {KEY}"
    if body is not None:
        h["Content-Type"] = "application/json"
    h.update(headers or {})
    c = conn()
    try:
        c.request(method, path, None if body is None else json.dumps(body), h)
        r = c.getresponse()
        raw = r.read()
        if owned_rows and r.status == 200:
            # Drop unowned list rows before anything else reads them.
            doc = json.loads(raw)
            doc["data"] = [row for row in doc.get("data", []) if row.get("id") in created]
            raw = _dump(doc).encode()
        return Resp(r.status, {k.lower(): v for k, v in r.getheaders()}, sanitize(raw))
    finally:
        c.close()


def call(method, path, body=None, expect=200, code=None, **kw):
    """Request and require exactly HTTP `expect` (and error code `code`, if given)."""
    r = request(method, path, body, **kw)
    where = f"{method} {path.split('?')[0]}"
    check(r.status == expect, f"{where}: HTTP {r.status}, {len(r.raw)} bytes, expected {expect}")
    check(code is None or r.code() == code, f"{where}: HTTP {r.status}, error code is not {code}")
    return r


def receipt(r, sid):
    """Require that every session id field in a receipt names the session that was asked about."""
    doc = r.json()
    ids = [v for v in ((doc.get("session") or {}).get("id"), doc.get("session_id"), doc.get("id")) if v is not None]
    check(ids and all(v == sid for v in ids), "a receipt names a different session")
    return r


def patch(sid, fields):
    """PATCH an owned session; the receipt must name it and carry exactly the values sent."""
    guard(sid)
    if "title" in fields:
        created[sid][1].add(fields["title"])  # before sending: a lost response leaves it confirmable
    r = receipt(call("PATCH", f"/api/sessions/{sid}", fields), sid)
    got = r.json()["session"]
    # Booleans by identity: 0/1 must not pass for False/True.
    check(all(got.get(k) is v if isinstance(v, bool) else got.get(k) == v for k, v in fields.items()),
          "PATCH receipt lacks the values sent")
    return r


def deleted_ok(r, sid):
    """A DELETE receipt must carry the id requested and deleted: true."""
    doc = r.json()
    check(doc.get("id") == sid and doc.get("deleted") is True, "DELETE receipt is not {id: requested, deleted: true}")
    return receipt(r, sid)


def delete(sid):
    guard(sid)
    return deleted_ok(call("DELETE", f"/api/sessions/{sid}"), sid)


def guard(session_id):
    # Hard rule: never touch a session this invocation does not own.
    check(session_id.startswith(PREFIX) and session_id in created, "refusing to touch an unowned session")


def title(name):
    return f"apofis-probe {TOKEN} {name} {secrets.token_hex(3)}"


def new_session(name, **extra):
    sid = f"{PREFIX}{int(time.time())}-{name}-{secrets.token_hex(16)}"
    t = title(name)
    created[sid] = (extra.get("source", "api_server"), {t})  # tracked before the POST; cleanup confirms ownership
    try:
        r = request("POST", "/api/sessions", {"id": sid, "title": t, **extra})
    except ProbeError:
        raise
    except Exception:
        raise ProbeError(f"create {name}: transport error (id stays tracked for cleanup)")
    if r.status == 409:
        del created[sid]  # not created by us: never delete
        raise ProbeError(f"create {name}: HTTP 409, id untracked and not deleted")
    check(r.status == 201, f"create {name}: HTTP {r.status}, {len(r.raw)} bytes, expected 201")
    receipt(r, sid)
    check(r.json()["session"].get("title") == t, f"create {name}: title not stored as sent")
    return sid, t, r


def list_by_title(t, extra=""):
    """GET /api/sessions filtered by a title this invocation sent; unowned rows are dropped."""
    check(bool(t and t.strip()), "refusing to list with an empty title")
    q = urllib.parse.urlencode({"source": "api_server", "title": t, "limit": 50})
    r = call("GET", f"/api/sessions?{q}{extra}", owned_rows=True)
    return r, [row["id"] for row in r.json()["data"]]


def messages(sid):
    guard(sid)
    return receipt(call("GET", f"/api/sessions/{sid}/messages?order=oldest&include_compacted=true"), sid)


def start_run(sid, text, idem=None, model_options=None):
    guard(sid)
    body = {"session_id": sid, "input": text}
    if model_options:
        body["model_options"] = model_options
    r = call("POST", "/v1/runs", body, expect=202, headers={"Idempotency-Key": idem} if idem else None)
    run_id = r.json()["run_id"]
    active_runs.append(run_id)
    check(r.json().get("status") == "started", "new run did not answer status started")
    return r, run_id, body


def status(run_id, sid):
    r = call("GET", f"/v1/runs/{run_id}")
    check(r.json().get("run_id") == run_id, "run status body names another run")
    return receipt(r, sid)


def wait_terminal(run_id, sid, timeout=RUN_TIMEOUT):
    end = time.time() + timeout
    while time.time() < end:
        r = status(run_id, sid)
        if r.json().get("status") in TERMINAL:
            if run_id in active_runs:
                active_runs.remove(run_id)
            return r
        time.sleep(1)
    raise ProbeError(f"run {run_id} not terminal after {timeout}s")


def wait_status(run_id, sid, wanted, timeout=60):
    end = time.time() + timeout
    while time.time() < end:
        r = status(run_id, sid)
        if r.json().get("status") in wanted:
            return r
        time.sleep(0.3)
    raise ProbeError(f"run {run_id} never reached {sorted(wanted)}")


def expect_status(r, wanted):
    check(r.json().get("status") == wanted, f"run status is not {wanted}")
    return r


def save(name, data):
    raw = sanitize(data.raw if isinstance(data, Resp) else data)
    check_shape(name, raw)
    pending[name] = raw


def publish():
    FIXTURES.mkdir(parents=True, exist_ok=True)
    for name, raw in pending.items():
        (FIXTURES / name).write_bytes(raw)
        print(f"    wrote {name}")
    pending.clear()


