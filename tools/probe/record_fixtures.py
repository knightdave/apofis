def sc_sessions():
    """create, duplicate, get, patch, archive, list by sent title, model lock, delete."""
    a, _, r = new_session("sessions-a")
    save("session_create.json", r)
    save("session_exists_409.json", call("POST", "/api/sessions", {"id": a, "title": title("again")},
                                         expect=409, code="session_exists"))
    b, tb, _ = new_session("sessions-b")
    c, tc, _ = new_session("sessions-c")

    ta = title("renamed")
    save("session_patch.json", patch(a, {"title": ta, "pinned": True}))
    save("session_patch_archived.json", patch(b, {"archived": True}))
    save("session_get_archived.json", receipt(call("GET", f"/api/sessions/{b}"), b))
    patch(c, {"pinned": True, "archived": True})
    save("session_patch_unsupported_400.json", call("PATCH", f"/api/sessions/{a}", {"color": "red"},
                                                    expect=400, code="unsupported_session_field"))

    r, ids = list_by_title(ta)
    check(ids == [a], "list by title did not return exactly the probe row")
    save("sessions_list.json", r)
    r, ids = list_by_title(tc)
    print(f"    pinned+archived row listed: {ids == [c]}")
    if ids == [c]:
        save("sessions_list_pinned_archived.json", r)
    for q in ("", "&archived=true", "&include_archived=true", "&archived_only=true", "&archived=1"):
        _, ids = list_by_title(tb, q)
        print(f"    list (title of archived row){q or ' default'}: includes it: {ids == [b]}")

    save("session_patch_unarchived.json", patch(b, {"archived": False}))

    # Per-session model lock with placeholder ids: the server does not validate them, no run starts.
    r = receipt(call("POST", f"/api/sessions/{a}/model", {"model": "example-model", "provider": "example-provider"}), a)
    check(r.json().get("runtime", {}).get("model_lock") == "accepted", "model lock not accepted")
    save("session_model_lock.json", r)
    save("session_get_model_locked.json", receipt(call("GET", f"/api/sessions/{a}"), a))

    save("session_delete.json", delete(c))
    save("session_recreate_deleted_409.json", call("POST", "/api/sessions", {"id": c, "title": title("recreate")},
                                                   expect=409, code="session_deleted"))
    return "ok"


