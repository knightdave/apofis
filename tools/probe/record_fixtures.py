class Stream(threading.Thread):
    """Reads one /events connection, keeps the raw bytes and the parsed events."""

    def __init__(self, run_id, last_event_id=None, stop_after=None):
        super().__init__(daemon=True)
        self.run_id, self.last_event_id, self.stop_after = run_id, last_event_id, stop_after
        self.raw = bytearray()
        self.events = []
        self.status = None
        self.closed = False  # saw ": stream closed"
        self.error = None
        self.cond = threading.Condition()

    def run(self):
        h = {"Authorization": f"Bearer {KEY}", "Accept": "text/event-stream"}
        if self.last_event_id is not None:
            h["Last-Event-ID"] = str(self.last_event_id)
        c = conn(timeout=90)
        try:
            c.request("GET", f"/v1/runs/{self.run_id}/events", headers=h)
            r = c.getresponse()
            self.status = r.status
            if r.status != 200:
                return
            data = []
            while True:
                line = r.readline()  # decodes chunked transfer encoding
                if not line:
                    break
                self.raw += line
                text = line.decode("utf-8").rstrip("\r\n")
                if text.startswith("data:"):
                    data.append(text[5:].lstrip())
                elif text.startswith(": stream closed"):
                    self.closed = True
                elif text == "" and data:
                    ev = json.loads("\n".join(data))
                    data = []
                    with self.cond:
                        self.events.append(ev)
                        self.cond.notify_all()
                    if self.stop_after and self.stop_after(ev):
                        break  # drop the connection right after a complete frame
        except Exception as exc:
            self.error = type(exc).__name__
        finally:
            c.close()
            with self.cond:
                self.cond.notify_all()

    def wait_for(self, pred, timeout=RUN_TIMEOUT):
        """First event matching pred, or None once the stream ended; raises on timeout."""
        end = time.time() + timeout
        with self.cond:
            while True:
                for ev in self.events:
                    if pred(ev):
                        return ev
                if not self.is_alive():
                    return None
                left = end - time.time()
                check(left > 0, f"stream {self.run_id}: nothing decisive within {timeout}s")
                self.cond.wait(min(left, 1))

    def names(self):
        return [e.get("event") for e in self.events]

    def require(self, last_event, start_seq=0, order=(), closed=True):
        """Complete, in-order stream for this run that ends with last_event."""
        sanitize(self.raw)
        n = len(self.events)
        check(self.status == 200, f"stream {self.run_id}: HTTP {self.status}")
        check(self.error is None, f"stream {self.run_id}: transport error")
        check(all(e.get("run_id") == self.run_id for e in self.events),
              f"stream {self.run_id}: an event names another run")
        check([e.get("seq") for e in self.events] == list(range(start_seq, start_seq + n)),
              f"stream {self.run_id}: sequence numbers missing or out of order ({n} events)")
        check("replay.truncated" not in self.names(), f"stream {self.run_id}: replay truncated")
        check(not closed or self.closed, f"stream {self.run_id}: no closing comment")
        check(n > 0 and self.events[-1].get("event") == last_event,
              f"stream {self.run_id}: does not end with {last_event}")
        check(sum(e in TERMINAL_EVENTS for e in self.names()) <= 1,
              f"stream {self.run_id}: more than one terminal event")
        names = self.names()
        pos = [names.index(e) if e in names else -1 for e in order]
        check(-1 not in pos and pos == sorted(pos), f"stream {self.run_id}: expected events missing or out of order")


def is_event(name):
    return lambda ev: ev.get("event") == name


def decisive(name):
    return lambda ev: ev.get("event") == name or ev.get("event") in TERMINAL_EVENTS


